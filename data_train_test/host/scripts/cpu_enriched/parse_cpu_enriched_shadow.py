def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8", errors="replace")).hexdigest()


def read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8-sig") as f:
        return json.load(f)


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, sort_keys=False)
        f.write("\n")


def write_md(path: Path, title: str, lines: Iterable[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        f.write(f"# {title}\n\n")
        for line in lines:
            f.write(f"{line}\n")


def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    with path.open("r", encoding="utf-8-sig") as f:
        for line_no, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_no}: JSON decode failed: {exc}") from exc
            row["_line_no"] = line_no
            row["_raw_hash"] = sha256_text(line)
            rows.append(row)
    return rows


def write_jsonl(path: Path, rows: Iterable[Dict[str, Any]]) -> int:
    count = 0
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, sort_keys=False) + "\n")
            count += 1
    return count


def command_id(row: Dict[str, Any]) -> str:
    return f"raw:{row.get('sample_index')}:{row.get('command_label')}:{row.get('_line_no')}"


def rows_by_label_and_sample(rows: List[Dict[str, Any]]) -> Dict[Tuple[int, str], Dict[str, Any]]:
    out: Dict[Tuple[int, str], Dict[str, Any]] = {}
    for row in rows:
        sample_index = int(row.get("sample_index", -1))
        label = str(row.get("command_label", ""))
        out[(sample_index, label)] = row
    return out


def rows_by_label(rows: List[Dict[str, Any]], label: str) -> List[Dict[str, Any]]:
    return [r for r in rows if r.get("command_label") == label]


def required_command_completeness(raw_rows: List[Dict[str, Any]]) -> Dict[str, Any]:
    sample_indices = sorted(
        {
            int(r.get("sample_index", -1))
            for r in raw_rows
            if int(r.get("sample_index", -1)) >= 0 and r.get("command_label") in REQUIRED_SAMPLE_COMMANDS
        }
    )
    if not sample_indices:
        return {
            "status": "NEEDS_FIX",
            "sample_count": 0,
            "required_command_count": len(REQUIRED_SAMPLE_COMMANDS),
            "empty_required_rows": 0,
            "missing_required_rows": len(REQUIRED_SAMPLE_COMMANDS),
            "empty_required_snapshot_rate": 1.0,
            "missing_by_sample": {},
            "empty_by_sample": {},
        }
    by_sample: Dict[int, Dict[str, str]] = defaultdict(dict)
    for row in raw_rows:
        label = str(row.get("command_label", ""))
        if label not in REQUIRED_SAMPLE_COMMANDS:
            continue
        sample = int(row.get("sample_index", -1))
        if sample < 0:
            continue
        by_sample[sample][label] = str(row.get("stdout", ""))
    missing_by_sample: Dict[int, List[str]] = {}
    empty_by_sample: Dict[int, List[str]] = {}
    empty_required_rows = 0
    missing_required_rows = 0
    for sample in sample_indices:
        for label in REQUIRED_SAMPLE_COMMANDS:
            if label not in by_sample.get(sample, {}):
                missing_by_sample.setdefault(sample, []).append(label)
                missing_required_rows += 1
                continue
            text = by_sample[sample][label].strip()
            if not text:
                empty_by_sample.setdefault(sample, []).append(label)
                empty_required_rows += 1
    total_required = len(sample_indices) * len(REQUIRED_SAMPLE_COMMANDS)
    bad_rows = empty_required_rows + missing_required_rows
    return {
        "status": "PASS" if bad_rows == 0 else "NEEDS_REPAIR",
        "sample_count": len(sample_indices),
        "required_command_count": len(REQUIRED_SAMPLE_COMMANDS),
        "empty_required_rows": empty_required_rows,
        "missing_required_rows": missing_required_rows,
        "empty_required_snapshot_rate": round(bad_rows / total_required, 4) if total_required else 1.0,
        "missing_by_sample": {str(k): v for k, v in sorted(missing_by_sample.items())},
        "empty_by_sample": {str(k): v for k, v in sorted(empty_by_sample.items())},
    }


def parse_cpu_line(line: str) -> Optional[Tuple[str, List[int]]]:
    parts = line.strip().split()
    if not parts or not parts[0].startswith("cpu"):
        return None
    values: List[int] = []
    for token in parts[1:]:
        try:
            values.append(int(token))
        except ValueError:
            values.append(0)
    return parts[0], values


def parse_proc_stat(text: str) -> Dict[str, Any]:
    cpus: Dict[str, List[int]] = {}
    procs_running = None
    procs_blocked = None
    for line in text.splitlines():
        parsed = parse_cpu_line(line)
        if parsed:
            name, values = parsed
            cpus[name] = values
        elif line.startswith("procs_running"):
            try:
                procs_running = int(line.split()[1])
            except Exception:
                procs_running = None
        elif line.startswith("procs_blocked"):
            try:
                procs_blocked = int(line.split()[1])
            except Exception:
                procs_blocked = None
    return {"cpus": cpus, "procs_running": procs_running, "procs_blocked": procs_blocked}


def cpu_busy_idle(values: List[int]) -> Tuple[int, int]:
    idle = (values[3] if len(values) > 3 else 0) + (values[4] if len(values) > 4 else 0)
    total = sum(values)
    busy = total - idle
    return busy, total


def cpu_util_between(prev: List[int], cur: List[int]) -> Optional[float]:
    prev_busy, prev_total = cpu_busy_idle(prev)
    cur_busy, cur_total = cpu_busy_idle(cur)
    total_delta = cur_total - prev_total
    if total_delta <= 0:
        return None
    busy_delta = cur_busy - prev_busy
    return max(0.0, min(1.0, busy_delta / total_delta))


def parse_loadavg(text: str) -> Dict[str, Any]:
    parts = text.strip().split()
    out: Dict[str, Any] = {"raw": text.strip()}
    if parts:
        try:
            out["load1"] = float(parts[0])
        except ValueError:
            out["load1"] = None
    if len(parts) >= 4 and "/" in parts[3]:
        left, right = parts[3].split("/", 1)
        try:
            out["runnable"] = int(left)
            out["total_threads"] = int(right)
        except ValueError:
            out["runnable"] = None
            out["total_threads"] = None
    return out


def parse_psi(text: str) -> Dict[str, Any]:
    out: Dict[str, Any] = {"available": False, "some": None, "full": None, "raw": text.strip()}
    if "UNAVAILABLE" in text:
        return out
    for line in text.splitlines():
        parts = line.split()
        if not parts:
            continue
        key = parts[0]
        values: Dict[str, float] = {}
        for token in parts[1:]:
            if "=" not in token:
                continue
            k, v = token.split("=", 1)
            try:
                values[k] = float(v)
            except ValueError:
                pass
        if key in {"some", "full"}:
            out[key] = values
            out["available"] = True
    return out


def parse_proc_pid_stat_line(line: str) -> Optional[Dict[str, Any]]:
    line = line.strip()
    if not line or line == "UNAVAILABLE":
        return None
    left = line.find("(")
    right = line.rfind(")")
    if left < 1 or right <= left:
        return None
    pid_text = line[:left].strip()
    comm = line[left + 1 : right]
    rest = line[right + 1 :].strip().split()
    if len(rest) < 22:
        return None
    try:
        pid = int(pid_text)
        state = rest[0]
        utime = int(rest[11])
        stime = int(rest[12])
        starttime = int(rest[19]) if len(rest) > 19 else None
    except ValueError:
        return None
    return {
        "pid": pid,
        "comm": comm,
        "state": state,
        "utime": utime,
        "stime": stime,
        "cpu_ticks": utime + stime,
        "starttime": starttime,
    }


def parse_pid_stat_all(text: str) -> Dict[int, Dict[str, Any]]:
    out: Dict[int, Dict[str, Any]] = {}
    for line in text.splitlines():
        parsed = parse_proc_pid_stat_line(line)
        if parsed:
            out[int(parsed["pid"])] = parsed
    return out


def parse_status(text: str) -> Dict[str, str]:
    out: Dict[str, str] = {}
    for line in text.splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        out[key.strip()] = value.strip()
    return out


def build_pid_details(rows: List[Dict[str, Any]]) -> Dict[int, Dict[str, Any]]:
    details: Dict[int, Dict[str, Any]] = defaultdict(dict)
    for row in rows:
        pid = row.get("pid")
        if pid is None:
            continue
        try:
            pid_i = int(pid)
        except (TypeError, ValueError):
            continue
        label = row.get("command_label")
        text = str(row.get("stdout", ""))
        if label == "proc_pid_status":
            details[pid_i]["status"] = parse_status(text)
        elif label == "proc_pid_stat":
            details[pid_i]["stat"] = parse_proc_pid_stat_line(text)
        elif label == "proc_pid_cpuset":
            details[pid_i]["cpuset"] = text.strip()
        elif label == "proc_pid_task_list":
            tids = []
            for line in text.splitlines():
                line = line.strip()
                if line.isdigit():
                    tids.append(int(line))
            details[pid_i]["task_list"] = tids
        elif label == "proc_pid_task_stat":
            stats = []
            for line in text.splitlines():
                parsed = parse_proc_pid_stat_line(line)
                if parsed:
                    stats.append(parsed)
            details[pid_i]["task_stats"] = stats
    return details


def derive_interval_rows(raw_rows: List[Dict[str, Any]], run_id: str) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    by = rows_by_label_and_sample(raw_rows)
    samples = sorted({int(r.get("sample_index", -1)) for r in raw_rows if int(r.get("sample_index", -1)) >= 0})
    detail_rows = [r for r in raw_rows if int(r.get("sample_index", -1)) == max(samples)]
    sample_indices = [s for s in samples if s < max(samples)]
    proc_stats = {s: parse_proc_stat(str(by.get((s, "proc_stat"), {}).get("stdout", ""))) for s in sample_indices}
    loads = {s: parse_loadavg(str(by.get((s, "proc_loadavg"), {}).get("stdout", ""))) for s in sample_indices}
    psis = {s: parse_psi(str(by.get((s, "proc_pressure_cpu"), {}).get("stdout", ""))) for s in sample_indices}
    pid_stats = {s: parse_pid_stat_all(str(by.get((s, "proc_pid_stat_all"), {}).get("stdout", ""))) for s in sample_indices}
    pid_details = build_pid_details(detail_rows)

    interval_rows: List[Dict[str, Any]] = []
    top_pid_sequence: List[Optional[int]] = []
    source_counter = 0
    for idx in range(1, len(sample_indices)):
        prev_i = sample_indices[idx - 1]
        cur_i = sample_indices[idx]
        prev_stat = proc_stats.get(prev_i, {})
        cur_stat = proc_stats.get(cur_i, {})
        prev_cpus = prev_stat.get("cpus", {})
        cur_cpus = cur_stat.get("cpus", {})
        per_core: Dict[str, float] = {}
        for core_name, cur_values in cur_cpus.items():
            if core_name == "cpu":
                continue
            prev_values = prev_cpus.get(core_name)
            if not prev_values:
                continue
            util = cpu_util_between(prev_values, cur_values)
            if util is not None:
                per_core[core_name] = round(util, 4)
        core_count = len(per_core)
        hot_core_count = sum(1 for value in per_core.values() if value >= 0.70)
        avg_util = round(sum(per_core.values()) / core_count, 4) if core_count else None

        prev_pids = pid_stats.get(prev_i, {})
        cur_pids = pid_stats.get(cur_i, {})
        proc_deltas = []
        total_proc_delta = 0
        for pid, cur in cur_pids.items():
            prev = prev_pids.get(pid)
            if not prev:
                continue
            delta = int(cur["cpu_ticks"]) - int(prev["cpu_ticks"])
            if delta < 0:
                continue
            total_proc_delta += delta
            proc_deltas.append((pid, delta, cur))
        proc_deltas.sort(key=lambda x: (-x[1], x[0]))
        top_proc = proc_deltas[0] if proc_deltas else None
        top_pid = top_proc[0] if top_proc else None
        top_pid_sequence.append(top_pid)
        dominant_process_ratio = round(top_proc[1] / total_proc_delta, 4) if top_proc and total_proc_delta > 0 else 0.0
        process_distribution = (
            "single_dominant" if dominant_process_ratio >= 0.60 else "distributed" if proc_deltas else "unknown"
        )

        load = loads.get(cur_i, {})
        runnable = load.get("runnable")
        load1 = load.get("load1")
        runnable_to_core_ratio = round(runnable / core_count, 4) if isinstance(runnable, int) and core_count else None
        load_to_core_ratio = round(load1 / core_count, 4) if isinstance(load1, float) and core_count else None
        procs_running = cur_stat.get("procs_running")
        oversub = bool(
            (runnable_to_core_ratio is not None and runnable_to_core_ratio > 1.0)
            or (load_to_core_ratio is not None and load_to_core_ratio > 1.25)
            or (isinstance(procs_running, int) and core_count and procs_running > core_count)
        )

        selected_detail = pid_details.get(top_pid or -1, {})
        status = selected_detail.get("status", {})
        task_stats = selected_detail.get("task_stats", [])
        task_list = selected_detail.get("task_list", [])
        top_thread = None
        if task_stats:
            top_thread = sorted(task_stats, key=lambda r: (-int(r.get("cpu_ticks", 0)), int(r.get("pid", 0))))[0]
        dominant_thread_ratio = 0.0
        if task_stats:
            total_thread_ticks = sum(int(t.get("cpu_ticks", 0)) for t in task_stats)
            if total_thread_ticks > 0 and top_thread:
                dominant_thread_ratio = round(int(top_thread.get("cpu_ticks", 0)) / total_thread_ticks, 4)
        thread_distribution = (
            "single_dominant" if dominant_thread_ratio >= 0.60 else "distributed" if task_stats else "unknown"
        )
        threads_value = status.get("Threads")
        try:
            selected_thread_count = int(threads_value) if threads_value is not None else len(task_list)
        except ValueError:
            selected_thread_count = len(task_list)

        single_spin = bool(dominant_process_ratio >= 0.60 and dominant_thread_ratio >= 0.50 and hot_core_count <= 1 and not oversub)
        multicore = bool((hot_core_count >= 2) or (avg_util is not None and avg_util >= 0.60 and dominant_process_ratio < 0.60))
        if oversub:
            route_hint = "oversub_like"
        elif multicore:
            route_hint = "multicore_like"
        elif single_spin:
            route_hint = "busy_loop_like"
        else:
            route_hint = "unknown"

        source_labels = [
            (prev_i, "proc_stat"),
            (cur_i, "proc_stat"),
            (cur_i, "proc_loadavg"),
            (cur_i, "proc_pressure_cpu"),
            (prev_i, "proc_pid_stat_all"),
            (cur_i, "proc_pid_stat_all"),
        ]
        source_refs = []
        for sample, label in source_labels:
            raw = by.get((sample, label))
            if raw:
                source_refs.append(command_id(raw))
        for raw in detail_rows:
            if raw.get("pid") == top_pid:
                source_refs.append(command_id(raw))
        source_counter += 1
        trace_ref = f"goal3av:{run_id}:interval:{cur_i}"
        top_process_identity = {
            "pid": top_pid,
            "name": top_proc[2].get("comm") if top_proc else None,
            "cpu_tick_delta": top_proc[1] if top_proc else 0,
            "dominant_process_ratio": dominant_process_ratio,
            "state": top_proc[2].get("state") if top_proc else None,
            "cpus_allowed_list": status.get("Cpus_allowed_list"),
            "cpuset": selected_detail.get("cpuset"),
        }
        top_thread_identity = {
            "tid": top_thread.get("pid") if top_thread else None,
            "name": top_thread.get("comm") if top_thread else None,
            "dominant_thread_ratio": dominant_thread_ratio,
            "scanned_thread_count": len(task_stats),
            "reported_thread_count": selected_thread_count,
        }
        model_visible = {
            "hot_core_count": hot_core_count,
            "dominant_process_ratio": dominant_process_ratio,
            "dominant_thread_ratio": dominant_thread_ratio,
            "runnable_to_core_ratio": runnable_to_core_ratio,
            "load_to_core_ratio": load_to_core_ratio,
            "route_hint": route_hint,
            "owner_review_required": route_hint == "unknown",
        }
        row = {
            "schema_version": "goal3av_cpu_enriched_row_v1",
            "timestamp": by.get((cur_i, "proc_stat"), {}).get("ended_at") or utc_now(),
            "run_id": run_id,
            "sample_index": cur_i,
            "phase": "shadow_cpu_enriched_dry_run",
            "per_core_cpu_utilization": per_core,
            "hot_core_count": hot_core_count,
            "top_cpu_process_identity": top_process_identity,
            "top_cpu_thread_identity": top_thread_identity,
            "process_count": len(cur_pids),
            "thread_count": loads.get(cur_i, {}).get("total_threads"),
            "runnable_queue_signal": {
                "runnable_tasks": runnable,
                "procs_running": procs_running,
                "procs_blocked": cur_stat.get("procs_blocked"),
                "runnable_to_core_ratio": runnable_to_core_ratio,
            },
            "oversubscription_signal": oversub,
            "single_process_spin_marker": single_spin,
            "multicore_saturation_signal": multicore,
            "process_distribution_signal": process_distribution,
            "thread_distribution_signal": thread_distribution,
            "sampling_consistency": "pending_cross_interval",
            "psi_cpu_some": psis.get(cur_i, {}).get("some"),
            "psi_cpu_full": psis.get(cur_i, {}).get("full"),
            "affinity_cpuset_summary": {
                "cpus_allowed_list": status.get("Cpus_allowed_list"),
                "cpuset": selected_detail.get("cpuset"),
            },
            "source_refs": source_refs,
            "safe_obs_flag": True,
            "candidate_visibility": "shadow_model_visible_summary_only",
            "model_visible_summary": model_visible,
            "trace_ref": trace_ref,
            "shadow_only": True,
            "not_for_training": True,
            "not_accepted": True,
            "active_contract": False,
            "production_baseline": False,
        }
        interval_rows.append(row)

    stable_top_pid = len({pid for pid in top_pid_sequence if pid is not None}) <= 1 and bool(top_pid_sequence)
    for row in interval_rows:
        row["sampling_consistency"] = "stable" if stable_top_pid else "low_sample_or_drifting"
        row["model_visible_summary"]["sampling_consistency"] = row["sampling_consistency"]
    meta = {
        "raw_sample_indices": sample_indices,
        "interval_count": len(interval_rows),
        "top_pid_sequence": top_pid_sequence,
        "stable_top_pid": stable_top_pid,
    }
    return interval_rows, meta


