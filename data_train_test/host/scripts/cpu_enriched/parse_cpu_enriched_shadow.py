def availability(rows: List[Dict[str, Any]], predicate) -> Dict[str, Any]:
    count = sum(1 for row in rows if predicate(row))
    total = len(rows)
    return {
        "available": count > 0,
        "count": count,
        "total": total,
        "rate": round(count / total, 4) if total else 0.0,
        "status": "available" if count > 0 else "unavailable",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw-samples", required=True)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--reports-dir", required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--target", required=True)
